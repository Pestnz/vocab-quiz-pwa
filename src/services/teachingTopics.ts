export const ALL_GENRES = Object.keys(TOPICS) as Genre[];

/** ジャンルを絞った場合はその中から、空なら(広め)全ジャンルから、直近に出していない話題を無作為に選ぶ */
export function pickTopic(genres: Genre[], recentTopics: string[], rand: () => number = Math.random): { genre: Genre; topic: string } {
  const useGenres = genres.length > 0 ? genres : ALL_GENRES;
  const pool: Array<{ genre: Genre; topic: string }> = [];
  for (const g of useGenres) {
    for (const t of TOPICS[g]) pool.push({ genre: g, topic: t });
  }
  const recent = new Set(recentTopics);
  const fresh = pool.filter((p) => !recent.has(p.topic));
  const from = fresh.length > 0 ? fresh : pool; // 出し切ったら、重複を許す
  return from[Math.floor(rand() * from.length)];
}
